PRAGMA foreign_keys = ON;

-- ---------------------------------------------------------------------
-- 1. Организации
-- ---------------------------------------------------------------------
CREATE TABLE "Организации" (
    "ID_Организации"        INTEGER PRIMARY KEY AUTOINCREMENT,
    "ПолноеНаименование"    TEXT NOT NULL,
    "ИНН"                   TEXT UNIQUE,
    "ОГРН"                  TEXT UNIQUE,
    "ЮридическийАдрес"      TEXT,
    "Телефон"               TEXT,
    "ЭлектроннаяПочта"      TEXT
);

-- ---------------------------------------------------------------------
-- 2. Сотрудники
-- ---------------------------------------------------------------------
CREATE TABLE "Сотрудники" (
    "ID_Сотрудника" INTEGER PRIMARY KEY AUTOINCREMENT,
    "ФИО"           TEXT NOT NULL,
    "Отдел"         TEXT,
    "Должность"     TEXT,
    "Email"         TEXT
);

-- ---------------------------------------------------------------------
-- 3. ОтветственныеЛица
-- ---------------------------------------------------------------------
CREATE TABLE "ОтветственныеЛица" (
    "ID_Ответственного" INTEGER PRIMARY KEY AUTOINCREMENT,
    "НомерПриказа"      TEXT,
    "ДатаПриказа"       TEXT,
    "ID_Сотрудника"     INTEGER NOT NULL,
    "ID_Организации"    INTEGER NOT NULL,
    FOREIGN KEY ("ID_Сотрудника")  REFERENCES "Сотрудники"("ID_Сотрудника")
        ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY ("ID_Организации") REFERENCES "Организации"("ID_Организации")
        ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX "idx_ОтвЛица_Сотрудник" ON "ОтветственныеЛица"("ID_Сотрудника");
CREATE INDEX "idx_ОтвЛица_Орг"       ON "ОтветственныеЛица"("ID_Организации");

-- ---------------------------------------------------------------------
-- 4. УполномоченныеЛица
-- ---------------------------------------------------------------------
CREATE TABLE "УполномоченныеЛица" (
    "ID_Уполномоченного" INTEGER PRIMARY KEY AUTOINCREMENT,
    "ОснованиеПолномочий" TEXT,
    "ID_Сотрудника"      INTEGER NOT NULL,
    "ID_Организации"     INTEGER NOT NULL,
    FOREIGN KEY ("ID_Сотрудника")  REFERENCES "Сотрудники"("ID_Сотрудника")
        ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY ("ID_Организации") REFERENCES "Организации"("ID_Организации")
        ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX "idx_УполнЛица_Сотрудник" ON "УполномоченныеЛица"("ID_Сотрудника");
CREATE INDEX "idx_УполнЛица_Орг"       ON "УполномоченныеЛица"("ID_Организации");

-- ---------------------------------------------------------------------
-- 5. КлассификаторОтраслей
-- ---------------------------------------------------------------------
CREATE TABLE "КлассификаторОтраслей" (
    "ID_Отрасли"      INTEGER PRIMARY KEY AUTOINCREMENT,
    "НаименованиеОтрасли" TEXT UNIQUE NOT NULL,
    "Код"             TEXT UNIQUE
);

-- ---------------------------------------------------------------------
-- 6. ТиповыеОбъектыКИИ
-- ---------------------------------------------------------------------
CREATE TABLE "ТиповыеОбъектыКИИ" (
    "ID_ТиповогоОбъекта" INTEGER PRIMARY KEY AUTOINCREMENT,
    "Наименование"       TEXT UNIQUE NOT NULL,
    "Тип"                TEXT,
    "Описание"           TEXT,
    "ID_Отрасли"         INTEGER NOT NULL,
    FOREIGN KEY ("ID_Отрасли") REFERENCES "КлассификаторОтраслей"("ID_Отрасли")
        ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX "idx_ТиповыеОбъекты_Отрасль" ON "ТиповыеОбъектыКИИ"("ID_Отрасли");

-- ---------------------------------------------------------------------
-- 7. ОбъектыКИИ (исправлено: убрано поле ID_Организации)
-- ---------------------------------------------------------------------
CREATE TABLE "ОбъектыКИИ" (
    "ID_Объекта"          INTEGER PRIMARY KEY AUTOINCREMENT,
    "Наименование"        TEXT NOT NULL,
    "ИнвентарныйНомер"    TEXT UNIQUE,
    "ДоменноеИмя"         TEXT,
    "IP_Адрес"            TEXT,
    "ДатаВвода"           TEXT,
    "Статус"              TEXT CHECK ("Статус" IN ('введен','эксплуатируется','выведен')),
    "ID_ТиповогоОбъекта"  INTEGER NOT NULL,
    "ID_Ответственного"   INTEGER NOT NULL,
    "ID_Уполномоченного"  INTEGER,
    FOREIGN KEY ("ID_ТиповогоОбъекта") REFERENCES "ТиповыеОбъектыКИИ"("ID_ТиповогоОбъекта")
        ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY ("ID_Ответственного")  REFERENCES "ОтветственныеЛица"("ID_Ответственного")
        ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY ("ID_Уполномоченного") REFERENCES "УполномоченныеЛица"("ID_Уполномоченного")
        ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX "idx_ОбъектыКИИ_Типовой"   ON "ОбъектыКИИ"("ID_ТиповогоОбъекта");
CREATE INDEX "idx_ОбъектыКИИ_Ответств"  ON "ОбъектыКИИ"("ID_Ответственного");
CREATE INDEX "idx_ОбъектыКИИ_Уполн"     ON "ОбъектыКИИ"("ID_Уполномоченного");

-- ---------------------------------------------------------------------
-- 8. ПоказателиКритериевЗначимости
-- ---------------------------------------------------------------------
CREATE TABLE "ПоказателиКритериевЗначимости" (
    "ID_Показателей"    INTEGER PRIMARY KEY AUTOINCREMENT,
    "Социальный"        NUMERIC,
    "Политический"      NUMERIC,
    "Экономический"     NUMERIC,
    "Экологический"     NUMERIC,
    "Оборонный"         NUMERIC,
    "ДатаРасчета"       TEXT
);

-- ---------------------------------------------------------------------
-- 9. АктыКатегорирования
-- ---------------------------------------------------------------------
CREATE TABLE "АктыКатегорирования" (
    "ID_Акта"                INTEGER PRIMARY KEY AUTOINCREMENT,
    "НомерАкта"              TEXT UNIQUE NOT NULL,
    "ДатаАкта"               TEXT,
    "Категория"              TEXT CHECK ("Категория" IN ('1','2','3','не присвоена')),
    "ДатаУтверждения"        TEXT,
    "НомерПротоколаКомиссии" TEXT,
    "ID_Объекта"             INTEGER NOT NULL,
    "ID_Показателей"         INTEGER NOT NULL,
    FOREIGN KEY ("ID_Объекта")     REFERENCES "ОбъектыКИИ"("ID_Объекта")
        ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY ("ID_Показателей") REFERENCES "ПоказателиКритериевЗначимости"("ID_Показателей")
        ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX "idx_Акты_Объект"    ON "АктыКатегорирования"("ID_Объекта");
CREATE INDEX "idx_Акты_Показатели" ON "АктыКатегорирования"("ID_Показателей");

-- ---------------------------------------------------------------------
-- 10. МероприятияПоВыводуИзЭксплуатации
-- ---------------------------------------------------------------------
CREATE TABLE "МероприятияПоВыводуИзЭксплуатации" (
    "ID_Мероприятия" INTEGER PRIMARY KEY AUTOINCREMENT,
    "Название"       TEXT NOT NULL,
    "ДатаНачала"     TEXT,
    "ДатаОкончания"  TEXT,
    "ТипМероприятия" TEXT,
    "Статус"         TEXT CHECK ("Статус" IN ('запланировано','выполняется','завершено')),
    "Описание"       TEXT,
    "ID_Объекта"     INTEGER NOT NULL,
    FOREIGN KEY ("ID_Объекта") REFERENCES "ОбъектыКИИ"("ID_Объекта")
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "idx_Меропр_Объект" ON "МероприятияПоВыводуИзЭксплуатации"("ID_Объекта");

-- ---------------------------------------------------------------------
-- 11. Документы
-- ---------------------------------------------------------------------
CREATE TABLE "Документы" (
    "ID_Документа"   INTEGER PRIMARY KEY AUTOINCREMENT,
    "ТипДокумента"   TEXT,
    "НомерДокумента" TEXT,
    "ДатаДокумента"  TEXT,
    "ИмяФайла"       TEXT,
    "Описание"       TEXT
);

-- ---------------------------------------------------------------------
-- 12. Объекты_Документы (связь M:N)
-- ---------------------------------------------------------------------
CREATE TABLE "Объекты_Документы" (
    "ID_Объекта"   INTEGER NOT NULL,
    "ID_Документа" INTEGER NOT NULL,
    "ДатаДобавления" TEXT,
    PRIMARY KEY ("ID_Объекта", "ID_Документа"),
    FOREIGN KEY ("ID_Объекта")   REFERENCES "ОбъектыКИИ"("ID_Объекта")
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY ("ID_Документа") REFERENCES "Документы"("ID_Документа")
        ON DELETE CASCADE ON UPDATE CASCADE
) WITHOUT ROWID;

